# ---------------------------------------------------------------- main

def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(2)
    b = load_brand(sys.argv[1])
    out = sys.argv[2]
    os.makedirs(os.path.join(out, "logos"), exist_ok=True)
    co = slug(g(b, "meta", "company", default="brand"))
    logo_files = {}
    for v in logo_variants(b):
        src = resolve(b, v.get("file"))
        if not src or not os.path.exists(src):
            continue
        base = f"{co}-logo-{slug(v.get('id'))}"
        ext = os.path.splitext(src)[1].lower()
        shutil.copy(src, os.path.join(out, "logos", base + ext))
        try:
            im = load_logo(src, target_px=2400)
            im.save(os.path.join(out, "logos", base + ".png"))
            logo_files[v.get("id")] = base + (ext if ext == ".svg" else ".png") + \
                (f" (+ {base}.png)" if ext == ".svg" else "")
        except Exception as e:  # noqa
            logo_files[v.get("id")] = base + ext
            print("WARN: could not export PNG for", v.get("id"), e)
    with open(os.path.join(out, "brand-guidelines.md"), "w") as f:
        f.write(build_markdown(b, logo_files))
    with open(os.path.join(out, "design-tokens.json"), "w") as f:
        json.dump(build_tokens(b), f, indent=2)
    with open(os.path.join(out, "tokens.css"), "w") as f:
        f.write(build_css(b))
    with open(os.path.join(out, "canva-brand-kit.md"), "w") as f:
        f.write(build_canva(b, logo_files))
    with open(os.path.join(out, "claude-design-setup.md"), "w") as f:
        f.write(build_claude(b))
    zp = os.path.join(out, "brand-handoff.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(out):
            for fn in files:
                p = os.path.join(root, fn)
                if os.path.abspath(p) == os.path.abspath(zp):
                    continue
                z.write(p, os.path.relpath(p, out))
    print("Wrote handoff kit to", out)
    for fn in sorted(os.listdir(out)):
        print(" -", fn)


if __name__ == "__main__":
    main()
