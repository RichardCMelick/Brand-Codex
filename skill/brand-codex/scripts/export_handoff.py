sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from brandlib import (load_brand, resolve, g, norm_hex, hex_to_rgb, parse_rgb,
                      contrast, wcag_label, color_by_ref, load_logo,
                      logo_variants, all_swatches)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", str(s).lower()).strip("-")


def bullet(items):
    return "\n".join(f"- {i}" for i in items if i)


def dont(x):
    """'Do not stretch it' -> "Don't: stretch it"."""
    x = str(x).strip()
    x = re.sub(r"^(do not|don't|never)\s+", "", x, flags=re.I)
    return "Don't: " + x[:1].lower() + x[1:]


def rule_text(r):
    return r if isinstance(r, str) else f"**{r.get('title')}:** {r.get('text')}"


# ---------------------------------------------------------------- tokens

def build_tokens(b):
    tok = {"color": {}, "mode": {}, "font": {}, "typography": {}}
    for grp, sw in all_swatches(b):
        h = norm_hex(sw.get("hex"))
        if not h:
            continue
        desc = "; ".join(x for x in [sw.get("role"), sw.get("pms") and f"PMS {sw['pms']}",
                                     sw.get("cmyk") and f"CMYK {sw['cmyk']}"] if x)
        t_ = {"$type": "color", "$value": h}
        if desc:
            t_["$description"] = desc
        tok["color"].setdefault(slug(grp), {})[slug(sw.get("name"))] = t_
    for m, spec in (g(b, "colors", "modes", default={}) or {}).items():
        out = {}
        for k, v in spec.items():
            c = color_by_ref(b, v)
            if c:
                out[slug(k)] = {"$type": "color", "$value": c}
        tok["mode"][m] = out
    for f in g(b, "typography", "families", default=[]) or []:
        fam = [f.get("name")] + ([f["fallback"]] if f.get("fallback") else []) + ["sans-serif"]
        tok["font"][slug(f.get("role") or f.get("name"))] = {"$type": "fontFamily", "$value": fam}
    for h in g(b, "typography", "hierarchy", default=[]) or []:
        v = {"fontFamily": h.get("family"), "fontWeight": h.get("weight"),
             "fontSize": h.get("size"), "lineHeight": h.get("line_height"),
             "letterSpacing": h.get("tracking"), "textCase": h.get("case")}
        tok["typography"][slug(h.get("level"))] = {
            "$type": "typography", "$value": {k: x for k, x in v.items() if x}}
    return {k: v for k, v in tok.items() if v}


WEIGHTS = {"thin": 100, "extralight": 200, "light": 300, "regular": 400, "book": 400,
           "medium": 500, "semibold": 600, "bold": 700, "extrabold": 800, "black": 900}


def css_weight(w):
    if w is None:
        return None
    k = str(w).lower().replace(" ", "").replace("-", "")
    return WEIGHTS.get(k, w)


def build_css(b):
    lines = ["/* Generated by Brand Codex from brand.json. Do not edit by hand. */", ":root {"]
    for grp, sw in all_swatches(b):
        h = norm_hex(sw.get("hex"))
        if h:
            lines.append(f"  --color-{slug(grp)}-{slug(sw.get('name'))}: {h};")
    for f in g(b, "typography", "families", default=[]) or []:
        stack = ", ".join([f'"{f.get("name")}"'] + ([f'"{f["fallback"]}"'] if f.get("fallback") else []) + ["sans-serif"])
        lines.append(f"  --font-{slug(f.get('role') or f.get('name'))}: {stack};")
    fams = {f.get("name"): slug(f.get("role") or f.get("name")) for f in g(b, "typography", "families", default=[]) or []}
    for h in g(b, "typography", "hierarchy", default=[]) or []:
        n = slug(h.get("level"))
        if h.get("family") in fams:
            lines.append(f"  --type-{n}-family: var(--font-{fams[h['family']]});")
        if h.get("size"):
            lines.append(f"  --type-{n}-size: {h['size']};")
        if css_weight(h.get("weight")):
            lines.append(f"  --type-{n}-weight: {css_weight(h['weight'])};")
        if h.get("line_height"):
            lines.append(f"  --type-{n}-line-height: {h['line_height']};")
    modes = g(b, "colors", "modes", default={}) or {}

    def mode_lines(m):
        out = []
        for k, v in (modes.get(m) or {}).items():
            c = color_by_ref(b, v)
            if c:
                out.append(f"  --{slug(k)}: {c};")
        return out
    lines += mode_lines("light")
    lines.append("}")
    if modes.get("dark"):
        lines += ["", "[data-theme=\"dark\"] {"] + mode_lines("dark") + ["}",
                  "", "@media (prefers-color-scheme: dark) {",
                  "  :root:not([data-theme=\"light\"]) {"] + \
                 ["  " + x for x in mode_lines("dark")] + ["  }", "}"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- markdown guide

def build_markdown(b, logo_files):
    co = g(b, "meta", "company", default="Company")
    M = []
    M.append(f"# {co} {g(b, 'meta', 'guide_title', default='Brand Guidelines')}")
    M.append(f"Version {g(b, 'meta', 'version', default='n/a')} | {g(b, 'meta', 'date', default='')}")
    if g(b, "meta", "purpose"):
        M.append(g(b, "meta", "purpose"))
    M.append("> Instructions for AI design tools: treat every value in this file as "
             "fixed. Use only the listed colors, typefaces, and logo files. Follow every "
             "\"Do not\" rule. If a request conflicts with this guide, follow the guide "
             "and say what you changed.")

    f = g(b, "foundation", default={}) or {}
    if f:
        M.append("## Brand foundation")
        for k, lab in (("mission", "Mission"), ("vision", "Vision"), ("tagline", "Tagline"),
                       ("positioning", "Positioning"), ("boilerplate", "Boilerplate")):
            if f.get(k):
                M.append(f"**{lab}:** {f[k]}")
        if f.get("direction") and f.get("direction_public", True):
            d = f["direction"]
            M.append("**Direction:** " + (" ".join(d) if isinstance(d, list) else d))
        for p in f.get("pillars") or []:
            M.append(f"### Pillar: {p.get('name')}\n{p.get('description', '')}\n" + bullet(p.get("points") or []))
        if f.get("values"):
            M.append("### Values\n" + bullet([v.get("name") + (f": {v.get('description')}" if v.get("description") else "")
                                             if isinstance(v, dict) else v for v in f["values"]]))
        v = f.get("voice") or {}
        if v:
            M.append("### Voice and tone")
            if v.get("summary"):
                M.append(v["summary"])
            if v.get("traits"):
                M.append("| We are | We are not |\n|---|---|\n" +
                         "\n".join(f"| {t.get('we_are')} | {t.get('we_are_not')} |" for t in v["traits"]))
            if v.get("tone_notes"):
                M.append(bullet(v["tone_notes"]))
    for a in g(b, "audiences", default=[]) or []:
        M.append(f"### Audience: {a.get('name')}\n{a.get('titles', '')}\n" + bullet(a.get("tone") or []))

    L = g(b, "logos", default={}) or {}
    if logo_variants(b):
        M.append("## Logo")
        if L.get("description"):
            M.append(L["description"])
        M.append("| Version | File | Use on | Usage |\n|---|---|---|---|")
        for vv in logo_variants(b):
            pref = " (preferred)" if vv.get("id") == L.get("preferred") else ""
            M.append(f"| {vv.get('name')}{pref} | logos/{logo_files.get(vv.get('id'), '')} | "
                     f"{vv.get('use_on')} backgrounds | {vv.get('usage', '')} |")
        cs = L.get("clear_space") or {}
        if cs:
            M.append(f"**Clear space:** {cs.get('rule') or cs.get('unit_description')}")
            if cs.get("small_size_rule"):
                M.append(f"**Small sizes:** {cs['small_size_rule']}")
        if L.get("min_size"):
            M.append("**Minimum size:** " + "; ".join(f"{k.replace('_', ' ')} {v}" for k, v in L["min_size"].items()))
        if L.get("trademark"):
            M.append(f"**Trademark:** {L['trademark']}")
        from misuse import GENERATORS
        auto = L.get("donts_auto") or ["stretch", "rotate", "recolor", "effects", "outline",
                                       "busy", "wrong_mode", "crowd"]
        donts = [GENERATORS[k][1] for k in auto if k in GENERATORS]
        donts += [d if isinstance(d, str) else d.get("text") for d in L.get("donts_custom") or []]
        M.append("### Logo: do not\n" + bullet(donts))
        if L.get("where_not"):
            M.append("### Where the logo never appears\n" + bullet(L["where_not"]))
        if L.get("lockup_rules"):
            M.append("### Lockups\n" + bullet(L["lockup_rules"]))
    A = g(b, "architecture")
    if A:
        M.append("## Brand architecture\n" + (A.get("intro") or ""))
        for t in A.get("tiers") or []:
            M.append(f"- **{t.get('name')}:** {t.get('rule', '')} Examples: {', '.join(t.get('examples') or [])}")
    C = g(b, "cobranding")
    if C:
        M.append("## Co-branding\n" + (C.get("intro") or ""))
        M.append(bullet([rule_text(r) for r in C.get("rules") or []]))
        if C.get("separator"):
            M.append(f"**Separator between logos:** {C['separator']}")
        if C.get("min_gap"):
            M.append(f"**Minimum gap:** {C['min_gap']}")
        if C.get("donts"):
            M.append("### Co-branding: do not\n" + bullet(C["donts"]))

    K = g(b, "colors", default={}) or {}
    if K.get("groups"):
        M.append("## Color")
        for grp in K["groups"]:
            M.append(f"### {grp.get('name')}\n{grp.get('usage', '')}")
            M.append("| Name | HEX | RGB | CMYK | Pantone | Role |\n|---|---|---|---|---|---|")
            for sw in grp.get("swatches", []):
                h = norm_hex(sw.get("hex")) or sw.get("hex")
                r = parse_rgb(sw.get("rgb")) or hex_to_rgb(h) or ""
                M.append(f"| {sw.get('name')} | {h} | {', '.join(map(str, r)) if r else ''} | "
                         f"{sw.get('cmyk', '')} | {sw.get('pms', '')} | {sw.get('role', '')} |")
        modes = K.get("modes") or {}
        if modes:
            M.append("### Light and dark mode")
            keys = ["background", "surface", "text", "text_muted", "border", "accent", "link", "logo_variant"]
            ms = [m for m in ("light", "dark") if modes.get(m)]
            M.append("| Token | " + " | ".join(m.title() for m in ms) + " |\n|---|" + "---|" * len(ms))
            for k in keys:
                row = []
                for m in ms:
                    v = modes[m].get(k)
                    c = color_by_ref(b, v) if k != "logo_variant" else None
                    row.append(f"{v} ({c})" if c and c != norm_hex(v) else str(v or ""))
                M.append(f"| {k} | " + " | ".join(row) + " |")
            for m in ms:
                bg = color_by_ref(b, modes[m].get("background"))
                tx = color_by_ref(b, modes[m].get("text"))
                if bg and tx:
                    r = contrast(bg, tx)
                    M.append(f"- {m.title()} mode body text contrast: {r:.1f}:1 ({wcag_label(r)})")
        if K.get("ratio"):
            M.append("### Proportion\n" + bullet([f"{i.get('label') or i.get('color')}: {i.get('percent')}%"
                                                  + (f" ({i['use']})" if i.get("use") else "") for i in K["ratio"]]))
        if K.get("gradients"):
            M.append("### Gradients\n" + (K.get("gradient_rules") or "") + "\n" +
                     bullet([f"{gd.get('name')}: {' to '.join(color_by_ref(b, c) or c for c in gd.get('stops', []))}"
                             + (f" at {gd['angle']} degrees" if gd.get("angle") is not None else "")
                             for gd in K["gradients"]]))
        if K.get("donts"):
            M.append("### Color: do not\n" + bullet(K["donts"]))

    T = g(b, "typography", default={}) or {}
    if T.get("families"):
        M.append("## Typography")
        for fm in T["families"]:
            M.append(f"- **{fm.get('name')}** ({fm.get('role', '')}): {fm.get('usage', '')} "
                     f"Weights: {', '.join(fm.get('weights') or [])}. "
                     f"Fallback: {fm.get('fallback', 'none')}. Source: {fm.get('source', 'n/a')}."
                     + (f" Reserved: {fm['reserved']}" if fm.get("reserved") else ""))
        if T.get("hierarchy"):
            M.append("| Level | Family | Weight | Size | Line height | Tracking | Case |\n|---|---|---|---|---|---|---|")
            for h in T["hierarchy"]:
                M.append(f"| {h.get('level')} | {h.get('family')} | {h.get('weight', '')} | {h.get('size', '')} | "
                         f"{h.get('line_height', '')} | {h.get('tracking', '')} | {h.get('case', '')} |")
        if T.get("rules"):
            M.append(bullet(T["rules"]))
        if T.get("donts"):
            M.append("### Typography: do not\n" + bullet(T["donts"]))

    I = g(b, "imagery", default={}) or {}
    for k, lab in (("photography", "Photography"), ("illustration", "Illustration"),
                   ("iconography", "Iconography"), ("graphic_elements", "Graphic elements")):
        sec = I.get(k)
        if not sec:
            continue
        if isinstance(sec, list):
            sec = {"principles": sec}
        M.append(f"## {lab}\n{sec.get('summary', '')}")
        M.append(bullet([rule_text(p) for p in sec.get("principles") or []]))
        if sec.get("dont"):
            M.append(f"### {lab}: avoid\n" + bullet(sec["dont"]))

    E = g(b, "editorial", default={}) or {}
    if E:
        M.append("## Writing style")
        if E.get("base_style_guide"):
            M.append(f"Base style guide: {E['base_style_guide']}.")
        if E.get("name_usage"):
            M.append("### Names\n" + bullet(E["name_usage"]))
        if E.get("terms"):
            M.append("| Use | Instead of | Note |\n|---|---|---|\n" +
                     "\n".join(f"| {t.get('use')} | {t.get('avoid')} | {t.get('note', '')} |" for t in E["terms"]))
        if E.get("formatting"):
            M.append("### Formatting\n" + bullet(E["formatting"]))
        if E.get("donts"):
            M.append("### Writing: do not\n" + bullet(E["donts"]))

    G = g(b, "governance", default={}) or {}
    if G:
        M.append("## Governance")
        if G.get("asset_location"):
            M.append(f"Files: {G['asset_location']}")
        for c in G.get("contacts") or []:
            M.append(f"- {c.get('role')}: {c.get('name', '')} {c.get('email', '')}")
        if G.get("checklist"):
            M.append("### Checklist\n" + bullet(G["checklist"]))
    return "\n\n".join(x for x in M if x and x.strip()) + "\n"


# ---------------------------------------------------------------- Canva

def build_canva(b, logo_files):
    co = g(b, "meta", "company", default="Company")
    fams = g(b, "typography", "families", default=[]) or []
    hier = {str(h.get("level", "")).lower(): h for h in g(b, "typography", "hierarchy", default=[]) or []}
    out = [f"# Set up the {co} Brand Kit in Canva",
           "Canva Brand Kits are available on Canva Pro, Teams, Business, Enterprise, "
           "Education, and Nonprofit plans. Menu names below may differ slightly as "
           "Canva updates its interface; the values are what matter.",
           "Open Canva, choose **Brand** in the side menu, and create a Brand Kit named "
           f"**{co}**. Then fill each area in this order."]
    out.append("## 1. Logos\nUpload these files from the `logos/` folder. Upload the SVG "
               "where one exists (scalable, print-ready) and the PNG as a backup. Name each "
               "upload exactly as listed so people pick the right one.")
    out.append("| Upload as | File | Use on |\n|---|---|---|\n" + "\n".join(
        f"| {co} logo: {v.get('name')} | {logo_files.get(v.get('id'), '')} | {v.get('use_on')} backgrounds |"
        for v in logo_variants(b)))
    out.append("## 2. Colors\nCreate one palette per group below, named as shown. Paste "
               "each HEX value exactly. Canva palettes hold HEX only, so keep this file for "
               "CMYK and Pantone values when briefing a printer.")
    for grp in g(b, "colors", "groups", default=[]) or []:
        out.append(f"**Palette: {co} {grp.get('name')}**\n" + "\n".join(
            f"- {sw.get('name')}: `{norm_hex(sw.get('hex'))}`" for sw in grp.get("swatches", [])))
    out.append("## 3. Fonts\nIf the brand fonts are not in Canva's library, upload the "
               "licensed font files (check your license allows it). Otherwise choose the "
               "fallback shown. Set the text styles:")
    def style(lv):
        h = hier.get(lv)
        return f"{h.get('family')} {h.get('weight', '')}, {h.get('size', '')}" if h else None
    rows = [("Title / Heading", style("h1") or (fams[0].get("name") if fams else "")),
            ("Subheading", style("h2") or style("h3") or ""),
            ("Body", style("body") or (fams[-1].get("name") if fams else ""))]
    out.append("\n".join(f"- **{a}:** {v}" for a, v in rows if v))
    out.append("Fallbacks: " + "; ".join(f"{f.get('name')} -> {f.get('fallback', 'none')}" for f in fams))
    v = g(b, "foundation", "voice", default={}) or {}
    if v or g(b, "foundation", "mission"):
        out.append("## 4. Brand voice\nPaste this into the Brand Voice section so Canva's "
                   "writing tools follow it:")
        txt = []
        if g(b, "foundation", "mission"):
            txt.append(f"Mission: {g(b, 'foundation', 'mission')}")
        if v.get("summary"):
            txt.append(v["summary"])
        for t in v.get("traits") or []:
            txt.append(f"We are {t.get('we_are')}, not {t.get('we_are_not')}.")
        txt += v.get("tone_notes") or []
        for tr in g(b, "editorial", "terms", default=[]) or []:
            txt.append(f"Say \"{tr.get('use')}\", not \"{tr.get('avoid')}\".")
        out.append("```\n" + "\n".join(txt) + "\n```")
    out.append("## 5. Guidelines\nIn the Brand Kit's guidelines area, add a short summary "
               "and do's and don'ts per category. Paste these:")
    L = g(b, "logos", default={}) or {}
    from misuse import GENERATORS
    auto = L.get("donts_auto") or ["stretch", "rotate", "recolor", "effects", "outline",
                                   "busy", "wrong_mode", "crowd"]
    ld = [GENERATORS[k][1] for k in auto if k in GENERATORS] + \
         [d if isinstance(d, str) else d.get("text") for d in L.get("donts_custom") or []] + \
         [f"Never place the logo {w[:1].lower() + w[1:]}" for w in L.get("where_not") or []]
    out.append("**Logos**\n```\n" + "\n".join(
        x for x in [f"Clear space: {g(b, 'logos', 'clear_space', 'rule') or ''}",
                    "Minimum size: " + "; ".join(f"{k.replace('_', ' ')} {v}" for k, v in (L.get("min_size") or {}).items())] if x.split(':')[1].strip())
        + "\n" + "\n".join(dont(d) for d in ld) + "\n```")
    cd = g(b, "colors", "donts", default=[]) or []
    ratio = g(b, "colors", "ratio", default=[]) or []
    out.append("**Colors**\n```\n" + "\n".join(
        [f"{i.get('label') or i.get('color')}: about {i.get('percent')}% of a layout" for i in ratio] +
        [dont(d) for d in cd]) + "\n```")
    td = (g(b, "typography", "rules", default=[]) or []) + [dont(d) for d in g(b, "typography", "donts", default=[]) or []]
    if td:
        out.append("**Fonts**\n```\n" + "\n".join(td) + "\n```")
    ph = g(b, "imagery", "photography", default={}) or {}
    if ph:
        out.append("**Photos**\n```\n" + (ph.get("summary") or "") + "\n" +
                   "\n".join(dont(d) for d in ph.get("dont") or []) + "\n```")
    out.append("## 6. Lock it down\nIf you are a Brand Kit admin, restrict editing of the "
               "kit and set brand controls so teammates can only use kit colors and fonts. "
               "Then make a template from one of the deck's slides to test the kit.")
    return "\n\n".join(out) + "\n"


