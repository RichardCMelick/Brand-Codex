#!/usr/bin/env python3
"""Export the brand as a handoff kit for other tools.

Writes into <out_dir>:
  brand-guidelines.md     complete written guide (humans and AI tools)
  design-tokens.json      W3C Design Tokens (DTCG) format
  tokens.css              CSS custom properties, light and dark
  canva-brand-kit.md      step-by-step Canva Brand Kit setup with exact values
  claude-design-setup.md  how to load the brand into Claude Design / Claude
  logos/                  original files plus transparent PNG exports
  brand-handoff.zip       everything above in one file

Usage: python export_handoff.py brand.json out_dir
"""

import json
